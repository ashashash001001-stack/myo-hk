def fix_chapter_file(tsx_path, pres_id, chap_dir, data):
    """Fix one chapter .tsx file. Returns True if changed."""
    content = tsx_path.read_text()
    original = content
    fname = tsx_path.stem  # e.g. "Size", "Content"
    title, sub, card, items = data

    # 1. Fix export function name
    content = re.sub(rf'^export function {fname.lower()}\b', f'export function {fname}', content, flags=re.MULTILINE)
    # Also catch "export default function name" pattern
    content = re.sub(rf'^export default function {fname.lower()}\b', f'export default function {fname}', content, flags=re.MULTILINE)

    # 2. Fix CSS import
    content = re.sub(rf'import ["\']\./{fname.lower()}\.css["\']', f'import "./{fname}.css"', content)

    # 3. Fix h1 title
    content = re.sub(r'<h1[^>]*className="c1-title"[^>]*>.*?</h1>', f'<h1 className="c1-title">{title}</h1>', content, flags=re.DOTALL)

    # 4. Fix p sub
    content = re.sub(r'<p[^>]*className="c1-sub"[^>]*>.*?</p>', f'<p className="c1-sub">{sub}</p>', content, flags=re.DOTALL)

    # 5. Fix card title
    content = re.sub(r'<h2[^>]*className="c1-card-title"[^>]*>.*?</h2>', f'<h2 className="c1-card-title">{card}</h2>', content, flags=re.DOTALL)

    # 6. Fix content items (the 5 <span> items inside the card list)
    for i, item in enumerate(items, 1):
        # Match <span>...</span> that contains the pattern like "1. ..." at start
        content = re.sub(
            rf'(<span[^>]*>){i}\.\s*[^<]*?(</span>)',
            rf'\g<1>{i}. {item}\g<2>',
            content
        )

    # 7. Fix step-1 number block (generic 4.9 / 5.0 / 4.8)
    content = re.sub(r'<span className="step-number">4\.[0-9]</span>', '<span className="step-number">1</span>', content)
    content = re.sub(r'<span className="step-number">5\.0</span>', '<span className="step-number">1</span>', content)

    if content != original:
        tsx_path.write_text(content)
        return True
    return False

def main():
    total = 0
    for pres_id, chapters in CONTENT.items():
        for chap_dir, data in chapters.items():
            pd = BASE / pres_id / "presentation" / "src" / "chapters" / chap_dir
            if not pd.exists():
                print(f"MISSING: {pd}")
                continue
            for tsx in pd.glob("*.tsx"):
                if tsx.name in ("Coldopen.tsx", "CTA.tsx", "narrations.ts"):
                    continue
                if fix_chapter_file(tsx, pres_id, chap_dir, data):
                    total += 1
                    print(f"  Fixed: {tsx.relative_to(BASE)}")

    print(f"\nTotal files fixed: {total}")

if __name__ == "__main__":
    main()